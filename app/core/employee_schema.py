"""Read-only contract of the actual, hash-checked bezPriznaku XSD component.

Only a bounded subset of XSD syntax is interpreted for construction. The real
XMLSchema validator remains authoritative. No values are generated by this layer.
"""
from __future__ import annotations

from dataclasses import dataclass
import json
from pathlib import Path
import re

from lxml import etree

from app.core.schemas import registered_validator
from app.core.xml_support import parse_local_xml

XS = "http://www.w3.org/2001/XMLSchema"


@dataclass(frozen=True)
class Particle:
    kind: str
    path: str
    qname: str
    minimum: int
    maximum: str
    children: tuple
    ids: tuple = ()
    file: str = ""
    line: int = 0
    type_name: str = ""
    base_type: str = ""

    def leaves(self):
        if self.kind == "leaf":
            return (self,)
        return tuple(leaf for child in self.children for leaf in child.leaves())


class EmployeeContract:
    def __init__(self, official_root: Path, bundle_id: str):
        self.validator = registered_validator(official_root, bundle_id)
        self.bundle = next(b for b in json.loads((official_root / "bundles.json").read_text(encoding="utf-8"))["bundles"] if b["id"] == bundle_id)
        self.types, self.elements, self.origins = {}, {}, {}
        resolver = self.validator.resolver
        for name in resolver.expected_hashes:
            document = parse_local_xml(resolver.read(resolver.root / name))
            namespace = document.get("targetNamespace")
            for node in document:
                if not isinstance(node.tag, str):
                    continue
                local = etree.QName(node).localname
                if local in {"simpleType", "complexType", "element"} and node.get("name"):
                    target = self.elements if local == "element" else self.types
                    target[(namespace, node.get("name"))] = node
            for node in document.iter():
                self.origins[node] = (name, namespace)
        root = next(n for (ns, name), n in self.elements.items() if name == "bezPriznaku")
        self.plan = self._node(root, "", (), 0)
        self.namespace = etree.QName(self.plan.qname).namespace
        self.fields = {p.path: p for p in self.plan.leaves()}
        if len(self.fields) != len(self.plan.leaves()):
            raise ValueError("Nejednoznačné cesty zaměstnaneckého schématu.")

    def _qname(self, node, value):
        prefix, name = value.split(":", 1) if ":" in value else (None, value)
        return node.nsmap.get(prefix), name

    def _node(self, node, parent, stack, depth):
        if depth > 40:
            raise ValueError("XSD kontrakt překračuje podporovanou hloubku.")
        kind = etree.QName(node).localname
        path, qname, ids, type_name = parent, "", (), node.get("type", "")
        file, namespace = self.origins[node]
        minimum, maximum = int(node.get("minOccurs", "1")), node.get("maxOccurs", "1")
        if minimum not in {0, 1}:
            raise ValueError("Tato XSD konstrukce vyžaduje další implementaci.")
        if kind == "element":
            if node.get("ref"):
                raise ValueError("Reference v payloadu vyžaduje další implementaci.")
            path = (parent + "/" if parent else "") + node.get("name")
            qname = "{" + namespace + "}" + node.get("name")
            documentation = " ".join(node.xpath("./xs:annotation/xs:documentation/text()", namespaces={"xs": XS}))
            ids = tuple(sorted(set(re.findall(r"\b10\d{3}\b", documentation))))
            complex_type = node.find("{" + XS + "}complexType")
            if complex_type is None and type_name:
                candidate = self.types.get(self._qname(node, type_name))
                if candidate is not None and etree.QName(candidate).localname == "complexType":
                    complex_type = candidate
            if complex_type is None:
                return Particle("leaf", path, qname, minimum, maximum, (), ids, file, node.sourceline, type_name, self._base(node))
            children = (self._node(complex_type, path, stack, depth + 1),)
        elif kind == "extension":
            key = self._qname(node, node.get("base"))
            if key in stack or key not in self.types:
                raise ValueError("Neznámá/cyklická XSD báze.")
            children = (self._node(self.types[key], path, stack + (key,), depth + 1),) + self._children(node, path, stack, depth)
        elif kind in {"complexType", "complexContent", "sequence", "choice"}:
            children = self._children(node, path, stack, depth)
        else:
            raise ValueError("Nepodporovaná konstrukce zaměstnaneckého XSD.")
        return Particle(kind, path, qname, minimum, maximum, children, ids, file, node.sourceline, type_name)

    def _children(self, node, path, stack, depth):
        return tuple(self._node(c, path, stack, depth + 1) for c in node
                     if isinstance(c.tag, str) and etree.QName(c).localname != "annotation")

    def _base(self, node, depth=0):
        if depth > 32:
            raise ValueError("Neplatná XSD báze.")
        value = node.get("type") or node.get("base")
        if value:
            key = self._qname(node, value)
            if key == ("http://schemas.cssz.cz/baseTypes/v2", "simpleNNType"):
                return "digit_string"
            if key[0] == XS:
                return key[1]
            return self._base(self.types[key], depth + 1)
        restriction = node.find(".//{" + XS + "}restriction")
        if restriction is not None:
            return self._base(restriction, depth + 1)
        return "string"

    def construct(self, values):
        """One instance per repeating element. No defaults, rounding or aggregation."""
        if set(values) - set(self.fields):
            raise ValueError("Pole není v konkrétním oficiálním kontraktu.")
        missing = []

        def active(p):
            return any(leaf.path in values for leaf in p.leaves())

        def emit(p, parent):
            if p.minimum == 0 and not active(p):
                return
            if p.kind == "leaf":
                if p.path not in values:
                    missing.append(p.path)
                else:
                    etree.SubElement(parent, p.qname).text = values[p.path]
                return
            if p.kind == "element":
                parent = etree.SubElement(parent, p.qname)
            if p.kind == "choice":
                selected = [c for c in p.children if active(c)]
                if len(selected) != 1:
                    missing.append(p.path + "/[jedna větev XSD choice]")
                    return
                emit(selected[0], parent)
            else:
                for child in p.children:
                    emit(child, parent)

        wrapper = etree.Element("inspection")
        emit(self.plan, wrapper)
        return wrapper[0], tuple(missing)
